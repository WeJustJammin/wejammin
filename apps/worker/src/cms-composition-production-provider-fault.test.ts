import { describe, expect, it, vi } from 'vitest';

import { createProductionCmsPatternInstanceDependencies } from './cms-composition-production-pattern';
import {
  BODY,
  compose,
  input,
  json,
} from './cms-composition-production.test-support';
import {
  environment,
  PARTY_ID,
  REQUEST_ID,
  USER_ID,
} from './cms-editorial-production.test-support';
import { PROVIDER_FAULTS } from './cms-composition-production-provider-fault.test-support';
import type {
  CmsPatternInstancePortInput,
  CmsPatternInstancePlacementResult,
} from './cms-composition/pattern-instance-routes';
import type {
  CmsTemplateContextPortInput,
  CmsTemplateDetailPortInput,
  CmsTemplateResult,
} from './cms-composition/template-routes';

/**
 * BE03c 1298-1302: "A response with an unmapped status or a message not generated by its
 * operation catalog is a contract failure and is treated as INTERNAL_ERROR 500 without leaking
 * the original payload." A PostgREST or PostgreSQL fault answered with a 4xx is not the caller's
 * refusal, whatever its HTTP status: every 03c production adapter scrubs it to 500, never to the
 * 401/403/404/409/422 the status alone would suggest and never to a retryable 503.
 */
const SCRUBBED = {
  ok: false,
  status: 500,
  code: 'INTERNAL_ERROR',
  details: {},
} as const;

const contextInput = (): CmsTemplateContextPortInput => ({
  ...input(),
  operationId: 'cmsTemplateContextRead',
});
const detailInput = (): CmsTemplateDetailPortInput => ({
  ...input(),
  operationId: 'cmsTemplateLatestRead',
  templateKey: 'profile-header',
});
const patternInput = (): CmsPatternInstancePortInput => ({
  operationId: 'CMS-03C-02',
  request: input().request,
  requestId: REQUEST_ID,
  session: {
    userId: USER_ID,
    actingPartyId: PARTY_ID,
    capabilities: ['cms.author'],
    mfaFresh: false,
  },
  body: {
    revisionId: 'd2000000-0000-4000-8000-000000000011',
    patternId: 'd2000000-0000-4000-8000-000000000012',
    patternVersion: 1,
    linkMode: 'linked',
    slotPath: '/primary',
    overrides: {},
    expectedVersion: '1',
  },
  idempotencyKey: 'pattern-command-0001',
  ifMatch: '1',
});
const signal = () => new AbortController().signal;

type Adapter = Readonly<{
  name: string;
  call: (
    fetchImpl: typeof fetch,
  ) => Promise<CmsTemplateResult<unknown> | CmsPatternInstancePlacementResult>;
}>;
const ADAPTERS: readonly Adapter[] = [
  {
    name: 'CMS-03C-01 define template',
    call: (fetchImpl) =>
      compose(fetchImpl).defineTemplate(
        input({ body: { ...BODY, templateKey: 'profile-header' } }),
        signal(),
      ),
  },
  {
    name: 'cmsTemplateContextRead',
    call: (fetchImpl) =>
      compose(fetchImpl).readContext(contextInput(), signal()),
  },
  {
    name: 'cmsTemplateLatestRead',
    call: (fetchImpl) => compose(fetchImpl).readLatest(detailInput(), signal()),
  },
  {
    name: 'CMS-03C-02 insert pattern instance',
    call: (fetchImpl) =>
      createProductionCmsPatternInstanceDependencies({
        environment,
        fetchImpl,
        humanOrigins: ['https://cms.example.test'],
        resolveSession: async () => ({
          ok: true,
          value: patternInput().session,
        }),
      }).insertPattern(patternInput(), signal()),
  },
];

describe.each(ADAPTERS)(
  '$name: provider 4xx without a product token',
  ({ call }) => {
    it.each(PROVIDER_FAULTS)(
      'scrubs %s to 500 INTERNAL_ERROR',
      async (_name, status, payload) => {
        const fetchImpl = vi.fn(async () => json(payload, status));
        const result = await call(fetchImpl as typeof fetch);
        expect(result).toMatchObject(SCRUBBED);
        expect(JSON.stringify(result)).not.toMatch(
          /PGRST|42702|actor_id|JWT|slow down|private/u,
        );
        expect(fetchImpl).toHaveBeenCalledTimes(1);
      },
    );

    it('does not let a faulting status borrow a refusal from the message prose', async () => {
      const result = await call(
        vi.fn(async () =>
          json(
            { code: 'PGRST202', message: 'NOT_FOUND capability_missing' },
            404,
          ),
        ) as typeof fetch,
      );
      expect(result).toMatchObject(SCRUBBED);
    });

    it.each([
      ['structured NOT_FOUND', 404, { code: 'NOT_FOUND' }, 404],
      [
        'P0001 NOT_FOUND',
        400,
        { code: 'P0001', message: 'NOT_FOUND', details: null },
        404,
      ],
      [
        '40001 VERSION_MISMATCH',
        409,
        { code: '40001', message: 'VERSION_MISMATCH' },
        409,
      ],
      ['structured INVALID_REQUEST', 400, { code: 'INVALID_REQUEST' }, 400],
    ] as const)(
      'keeps the product answer for %s',
      async (_name, providerStatus, payload, status) => {
        const result = await call(
          vi.fn(async () => json(payload, providerStatus)) as typeof fetch,
        );
        expect(result).toMatchObject({ ok: false, status });
      },
    );

    it('keeps a provider outage a retryable 503 and does not scrub it to 500', async () => {
      const result = await call(
        vi.fn(async () => json({ code: 'PGRST000' }, 503)) as typeof fetch,
      );
      expect(result).toMatchObject({
        ok: false,
        status: 503,
        code: 'DEPENDENCY_UNAVAILABLE',
      });
    });
  },
);
